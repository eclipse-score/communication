/// Field subscriber type which implements the FieldSubscriber trait for Mock runtime.
pub struct MockFieldSubscriber<T: CommData + Debug> {
    identifier: &'static str,
    instance_info: MockConsumerInfo,
    _data: PhantomData<T>,
}

/// Marker implementation of FieldSubscriber trait.
/// Field get/set are exposed as async MethodCaller-based wrappers on the consumer struct
/// generated by the interface! macro; they are not part of FieldSubscriber itself.
impl<T: CommData + Debug> FieldSubscriber<T, MockRuntimeImpl> for MockFieldSubscriber<T> {}

/// Implementation of Subscriber trait for MockFieldSubscriber.
impl<T: CommData + Debug> Subscriber<T, MockRuntimeImpl> for MockFieldSubscriber<T> {
    type Subscription = MockFieldSubscription<T>;

    fn new(identifier: &'static str, instance_info: MockConsumerInfo) -> Result<Self> {
        Ok(Self {
            identifier,
            instance_info,
            _data: PhantomData,
        })
    }

    fn subscribe(self, max_num_samples: usize) -> Result<Self::Subscription> {
        if max_num_samples == 0 {
            return Err(Error::EventError(EventFailedReason::InvalidMaxSamples));
        }
        let subscription = MockFieldSubscription {
            identifier: self.identifier,
            instance_info: self.instance_info,
            _data: PhantomData,
        };
        subscription.with_state(|state| state.capacity = max_num_samples)?;
        Ok(subscription)
    }
}

/// FieldSubscription type which provides data receiving APIs and unsubscribe method.
pub struct MockFieldSubscription<T: CommData + Debug> {
    identifier: &'static str,
    instance_info: MockConsumerInfo,
    _data: PhantomData<T>,
}

impl<T: CommData + Debug> MockFieldSubscription<T> {
    fn key(&self) -> RegistryKey {
        make_key(&self.instance_info.instance_specifier, self.identifier)
    }

    fn with_state<Rt>(&self, f: impl FnOnce(&mut FieldState<T>) -> Rt) -> Result<Rt> {
        with_field_state::<T, Rt>(&self.key(), f)
    }

    /// Move up to `max_samples` pending field values from the per-field queue into `scratch`.
    ///
    /// Note: if `scratch` runs out of capacity mid-drain, the sample that did not fit is
    /// dropped and the error is returned - size the container for `max_samples` in tests.
    fn drain_into<'x>(&self, scratch: &mut SampleContainer<MockSample<'x, T>>, max_samples: usize) -> Result<usize> {
        let mut delivered = 0;
        while delivered < max_samples {
            let value = match self.with_state(|state| state.queue.pop_front())? {
                Some(value) => value,
                None => break,
            };
            scratch.push_back(MockSample::from(value))?;
            delivered += 1;
        }
        Ok(delivered)
    }
}

impl<T: CommData + Debug> FieldSubscription<T, MockRuntimeImpl> for MockFieldSubscription<T> {
    fn get_free_sample_count(&self) -> Result<usize> {
        self.with_state(|state| state.capacity.saturating_sub(state.queue.len()))
    }

    fn get_num_new_samples_available(&self) -> Result<usize> {
        self.with_state(|state| state.queue.len())
    }
}

/// Implementation of Subscription trait which provides receiving APIs.
impl<T: CommData + Debug> Subscription<T, MockRuntimeImpl> for MockFieldSubscription<T> {
    type Subscriber = MockFieldSubscriber<T>;
    type Sample<'a>
        = MockSample<'a, T>
    where
        Self: 'a;

    fn unsubscribe(self) -> Self::Subscriber {
        MockFieldSubscriber {
            identifier: self.identifier,
            instance_info: self.instance_info,
            _data: PhantomData,
        }
    }

    fn try_receive<'a>(
        &'a self,
        scratch: &'_ mut SampleContainer<Self::Sample<'a>>,
        max_samples: usize,
    ) -> Result<usize> {
        self.drain_into(scratch, max_samples)
    }

    /// Waits (by re-polling; the mock has no wakeup infrastructure) until at least
    /// `max(new_samples, 1)` values are pending, then drains up to `max_samples` of them.
    /// Resolves with `ReceiveFailedReason::Cancelled` once `cancellation` completes.
    #[allow(clippy::manual_async_fn)]
    fn cancellable_receive<'a>(
        &'a self,
        scratch: SampleContainer<Self::Sample<'a>>,
        new_samples: usize,
        max_samples: usize,
        cancellation: impl Future<Output = ()> + Send + 'static,
    ) -> impl Future<Output = (SampleContainer<Self::Sample<'a>>, Result<usize>)> + 'a {
        async move {
            let mut scratch = scratch;
            let mut cancellation = Box::pin(cancellation);
            let required = new_samples.max(1);
            let result = futures::future::poll_fn(|cx| {
                if cancellation.as_mut().poll(cx).is_ready() {
                    return Poll::Ready(Err(Error::ReceiveError(ReceiveFailedReason::Cancelled)));
                }
                let available = match self.with_state(|state| state.queue.len()) {
                    Ok(available) => available,
                    Err(e) => return Poll::Ready(Err(e)),
                };
                if available >= required {
                    return Poll::Ready(self.drain_into(&mut scratch, max_samples));
                }
                // No wakeup infrastructure in the mock: request an immediate re-poll.
                cx.waker().wake_by_ref();
                Poll::Pending
            })
            .await;
            (scratch, result)
        }
    }

    fn to_stream<'a>(&'a mut self) -> impl Stream<Item = Result<Self::Sample<'a>>> + Unpin + 'a {
        stream::empty()
    }
}

