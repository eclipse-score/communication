/// Registry key: `(instance specifier, endpoint name)`.
/// The endpoint name is the method name, the field name, or `{field}_get` / `{field}_set`
/// for the field get/set callers generated by the `interface!` macro.
type RegistryKey = (String, String);

/// Type-erased, registered method handler. The stored closure owns the user handler and
/// takes `Args` by value so that handlers with by-value semantics (field set) can be bridged.
struct StoredHandler<Args, Return> {
    f: Arc<dyn Fn(Args) -> BoxFuture<'static, Return> + Send + Sync>,
}

/// Per-field mock state: pending updates and the subscription capacity.
struct FieldState<T> {
    queue: VecDeque<T>,
    capacity: usize,
}

impl<T> FieldState<T> {
    fn new() -> Self {
        Self {
            queue: VecDeque::new(),
            capacity: usize::MAX,
        }
    }
}

#[derive(Default)]
struct MockRegistry {
    handlers: Mutex<HashMap<RegistryKey, Arc<dyn Any + Send + Sync>>>,
    fields: Mutex<HashMap<RegistryKey, Arc<dyn Any + Send + Sync>>>,
}

fn registry() -> &'static MockRegistry {
    static REGISTRY: OnceLock<MockRegistry> = OnceLock::new();
    REGISTRY.get_or_init(MockRegistry::default)
}

fn make_key(instance: &InstanceSpecifier, endpoint: &str) -> RegistryKey {
    (instance.as_ref().to_string(), endpoint.to_string())
}

/// Register (or replace) the handler stored under `key`.
fn register_erased_handler<Args, Return>(
    key: RegistryKey,
    f: impl Fn(Args) -> BoxFuture<'static, Return> + Send + Sync + 'static,
) where
    Args: MethodArgs,
    Return: CommData,
{
    let stored: StoredHandler<Args, Return> = StoredHandler { f: Arc::new(f) };
    registry()
        .handlers
        .lock()
        .expect("mock handler registry poisoned")
        .insert(key, Arc::new(stored));
}

/// Look up the handler stored under `key`, checking that argument and return types match.
#[allow(clippy::type_complexity)]
fn lookup_erased_handler<Args, Return>(
    key: &RegistryKey,
) -> Result<Arc<dyn Fn(Args) -> BoxFuture<'static, Return> + Send + Sync>>
where
    Args: MethodArgs,
    Return: CommData,
{
    let map = registry().handlers.lock().expect("mock handler registry poisoned");
    let entry = map
        .get(key)
        .ok_or(Error::MethodError(MethodFailedReason::HandlerNotRegistered))?;
    let stored = entry
        .downcast_ref::<StoredHandler<Args, Return>>()
        .ok_or(Error::MethodError(MethodFailedReason::TypeMismatch))?;
    Ok(Arc::clone(&stored.f))
}

/// Run `f` with exclusive access to the field state stored under `key`,
/// creating the state on first use.
fn with_field_state<T, Rt>(key: &RegistryKey, f: impl FnOnce(&mut FieldState<T>) -> Rt) -> Result<Rt>
where
    T: CommData + Debug,
{
    let mut map = registry().fields.lock().expect("mock field registry poisoned");
    let entry = map
        .entry(key.clone())
        .or_insert_with(|| Arc::new(Mutex::new(FieldState::<T>::new())));
    let state = entry
        .downcast_ref::<Mutex<FieldState<T>>>()
        .ok_or(Error::MethodError(MethodFailedReason::TypeMismatch))?;
    let mut guard = state.lock().expect("mock field state poisoned");
    Ok(f(&mut guard))
}

/// Push a field value into the per-field queue (ring semantics: the oldest value is
/// dropped once the subscription capacity is reached).
fn push_field_value<T>(key: &RegistryKey, value: T) -> Result<()>
where
    T: CommData + Debug,
{
    with_field_state::<T, _>(key, |state| {
        if state.queue.len() >= state.capacity {
            state.queue.pop_front();
        }
        state.queue.push_back(value);
    })
}

