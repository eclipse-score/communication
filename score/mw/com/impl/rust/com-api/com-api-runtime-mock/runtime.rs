//! This crate provides a mock implementation of the COM API for testing purposes.
//! It is meant to be used in conjunction with the `com-api` crate.
//! The mock implementation does not perform any real IPC and is not meant to be used in production.
//! It is only meant to be used for testing and development.
//!
//! # Method and Field support
//!
//! Methods and fields are routed through a process-local registry keyed by
//! `(instance specifier, endpoint name)`:
//!
//! - A producer-side [`MockMethodHandler`] registers its handler in the registry; a
//!   consumer-side [`MockMethodCaller`] for the same instance and method name looks the
//!   handler up, invokes it in-process and returns the result. No IPC takes place.
//! - Field get/set reuse the Method infrastructure: [`MockFieldPublisher`] registers its
//!   get/set callbacks under `{field}_get` / `{field}_set`, matching the caller names
//!   generated by the `interface!` macro.
//! - Field updates ([`FieldPublisher::update`] and [`FieldSampleMut::update`]) are pushed
//!   into a per-field queue which field subscriptions of the same instance drain.
//!
//! # Mock limitations (by design, documented for test authors)
//!
//! - `CommData` does not provide `Clone`, so one value cannot be fanned out to several
//!   receivers. Field updates are therefore delivered to a single shared per-field queue:
//!   concurrent subscriptions of the same field steal from each other.
//! - For the same reason, a field `set` returns the accepted value to the caller but does
//!   not additionally commit it to subscribers, and a field `get` requires a registered
//!   get handler (there is no "latest value" fallback).
//! - `invoke_zero_copy` returns [`MethodFailedReason::ZeroCopyNotSupported`]: the concept
//!   crate currently offers a runtime no generic way to consume `PtrTuple`
//!   (`MethodArgsPtrTuple` exposes only the type, no per-arity destructuring), so a
//!   runtime-side dispatch of the zero-copy path cannot be written without new concept
//!   support. The allocation and `write()` half of the zero-copy path is functional.

