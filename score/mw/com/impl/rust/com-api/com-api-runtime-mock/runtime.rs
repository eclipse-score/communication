/// Consumer-side mock method caller. `invoke_with_copy` looks up the handler registered
/// under `(instance specifier, method name)` and invokes it in-process.
pub struct MockMethodCaller<Args: MethodArgs, Return: CommData, R: Runtime> {
    key: RegistryKey,
    _phantom: core::marker::PhantomData<(Args, Return, R)>,
}

impl<Args: MethodArgs, Return: CommData> MethodCaller<Args, Return, MockRuntimeImpl>
    for MockMethodCaller<Args, Return, MockRuntimeImpl>
{
    fn new(method_name: &str, instance_info: MockConsumerInfo) -> Result<Self>
    where
        Self: Sized,
    {
        Ok(MockMethodCaller {
            key: make_key(&instance_info.instance_specifier, method_name),
            _phantom: core::marker::PhantomData,
        })
    }

    #[allow(clippy::manual_async_fn)]
    fn invoke_with_copy<'a>(&'a self, args: Args) -> impl Future<Output = Result<MockMethodReturnSample<Return>>> + 'a {
        async move {
            let handler = lookup_erased_handler::<Args, Return>(&self.key)?;
            let value = handler(args).await;
            Ok(MockMethodReturnSample { value })
        }
    }

    fn allocate(&self) -> Result<<Args as MethodArgsAllocate<MockMethodInArgAllocator>>::UninitTuple>
    where
        Args: MethodArgsAllocate<MockMethodInArgAllocator>,
    {
        Ok(<Args as MethodArgsAllocate<MockMethodInArgAllocator>>::alloc_uninit(
            &MockMethodInArgAllocator,
        ))
    }

    /// Zero-copy dispatch is not supported by the mock runtime: `MethodArgsPtrTuple`
    /// exposes only the pointer-tuple *type* and no per-arity way to destructure it, so no
    /// runtime can generically consume `ptrs` without additional concept support.
    /// The copy path (`invoke_with_copy`) covers the mock's routing semantics.
    #[allow(clippy::manual_async_fn)]
    fn invoke_zero_copy<'a>(
        &'a self,
        _ptrs: <Args as MethodArgsPtrTuple<MockRuntimeImpl>>::PtrTuple,
    ) -> impl Future<Output = Result<MockMethodReturnSample<Return>>> + 'a
    where
        Args: MethodArgsPtrTuple<MockRuntimeImpl>,
    {
        async move { Err(Error::MethodError(MethodFailedReason::ZeroCopyNotSupported)) }
    }
}

