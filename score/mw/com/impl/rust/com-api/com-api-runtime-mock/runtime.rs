/// Producer-side mock method handler. Registering a handler stores it in the
/// process-local registry under `(instance specifier, method name)` so that a
/// [`MockMethodCaller`] created with the same key can invoke it in-process.
pub struct MockMethodHandler<Args: MethodArgs, Return: CommData, R: Runtime + ?Sized> {
    key: RegistryKey,
    _phantom: core::marker::PhantomData<(Args, Return, R)>,
}

impl<Args: MethodArgs, Return: CommData> MethodHandler<Args, Return, MockRuntimeImpl>
    for MockMethodHandler<Args, Return, MockRuntimeImpl>
{
    fn new(method_name: &str, instance_info: MockProviderInfo) -> Result<Self>
    where
        Self: Sized,
    {
        Ok(MockMethodHandler {
            key: make_key(&instance_info.instance_specifier, method_name),
            _phantom: core::marker::PhantomData,
        })
    }

    fn register_handler<F>(&self, handler: F)
    where
        F: MethodHandlerCall<Args, Return>,
    {
        // Bridge the by-reference `MethodHandlerCall` contract to the registry's by-value
        // closure: the handler future must not borrow the arguments (see trait docs), so the
        // arguments can be dropped as soon as `call` returns the future.
        register_erased_handler::<Args, Return>(self.key.clone(), move |args: Args| handler.call(&args).boxed());
    }
}

