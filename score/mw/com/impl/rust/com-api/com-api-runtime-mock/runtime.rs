impl<T: CommData + Debug> FieldPublisher<T, MockRuntimeImpl> for MockFieldPublisher<T> {
    type SampleMaybeUninit<'a>
        = MockFieldSampleMaybeUninit<'a, T>
    where
        Self: 'a;

    fn new(identifier: &'static str, instance_info: MockProviderInfo) -> Result<Self> {
        let key = make_key(&instance_info.instance_specifier, identifier);
        // Create the field state eagerly so updates published before any subscription are kept.
        with_field_state::<T, _>(&key, |_| ())?;
        Ok(Self {
            key,
            _data: PhantomData,
        })
    }

    fn allocate(&self) -> Result<Self::SampleMaybeUninit<'_>> {
        Ok(MockFieldSampleMaybeUninit {
            data: MaybeUninit::uninit(),
            key: self.key.clone(),
            _lifetime: PhantomData,
        })
    }

    fn update(&self, value: T) -> Result<()> {
        push_field_value(&self.key, value)
    }

    /// Stores the set handler under `{field}_set`, matching the caller name generated by
    /// the `interface!` macro for `R::FieldSetCaller<T>`.
    ///
    /// Mock limitation: the accepted value is returned to the set caller but is NOT also
    /// committed to subscribers; `CommData` provides no way to duplicate the value for both
    /// paths. Tests that need subscriber delivery combine `set` with an explicit `update()`.
    fn register_set_handler<F, Fut>(&self, callback: F)
    where
        F: Fn(T) -> Fut + Send + Sync + 'static,
        Fut: core::future::Future<Output = T> + Send + 'static,
    {
        let key = (self.key.0.clone(), format!("{}_set", self.key.1));
        register_erased_handler::<(T,), T>(key, move |args: (T,)| {
            let (proposed,) = args;
            callback(proposed).boxed()
        });
    }

    /// Stores the get handler under `{field}_get`, matching the caller name generated by
    /// the `interface!` macro for `R::FieldGetCaller<T>`.
    ///
    /// Mock limitation: unlike the C++ default-get behaviour, the mock has no
    /// latest-value fallback (duplicating the stored value would require `Clone` on
    /// `CommData`), so a get without a registered handler fails with
    /// `MethodFailedReason::HandlerNotRegistered`.
    fn register_get_handler(&self, callback: impl Fn() -> T + Send + Sync + 'static) {
        let key = (self.key.0.clone(), format!("{}_get", self.key.1));
        register_erased_handler::<(), T>(key, move |_args: ()| futures::future::ready(callback()).boxed());
    }
}

