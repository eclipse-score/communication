//! Validation tests for the code generated by the `interface!` macro.
//!
//! These tests need the `score_com` crate, which itself depends on `score_com_concept`. They are
//! therefore built as a standalone test crate instead of being part of `score_com_concept`, to
//! avoid a circular crate dependency.

#![allow(dead_code)]
#![allow(unused_imports)]

#[test]
fn test_interface_id_auto_generated() {
    mod test_module {
        use score_com::{CommData, ProviderInfo, Publisher, Reloc, Subscriber};

        #[derive(Debug, Reloc)]
        #[repr(C)]
        pub struct Tire {
            pub pressure: f32,
        }
        impl CommData for Tire {
            const ID: &'static str = "Tire";
        }

        score_com::interface!(
            interface Vehicle {
                left_tire: Event<Tire>,
            }
        );

        pub fn validate() {
            // Referencing VehicleInterface by name is itself proof the type was generated;
            // the compiler enforces the name at compile time.
            let interface_id = <VehicleInterface as score_com::Interface>::INTERFACE_ID;
            let expected_id = concat!(module_path!(), "::", "Vehicle");
            assert_eq!(interface_id, expected_id, "Interface ID mismatch for VehicleInterface");
        }
    }
    test_module::validate();
}

